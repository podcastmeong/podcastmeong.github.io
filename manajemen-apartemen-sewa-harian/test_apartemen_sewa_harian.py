def text(page, sel):
    el = page.query_selector(sel)
    return el.inner_text() if el else ""


def rupiah(n):
    return "Rp" + f"{n:,}".replace(",", ".")


def harga(tarif, ci, co, pengali=1.2, diskon_persen=10, min_malam=7):
    """Replika aturan harga JS: Jumat(4)/Sabtu(5) x pengali; diskon bila >= min_malam."""
    total = 0
    d = ci
    malam = (co - ci).days
    while d < co:
        t = tarif
        if d.weekday() in (4, 5):
            t = round(t * pengali)
        total += t
        d += timedelta(days=1)
    diskon = round(total * diskon_persen / 100) if malam >= min_malam else 0
    return malam, total - diskon, diskon


